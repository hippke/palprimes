import json, sys
d = json.load(open(sys.argv[1]))
Q = d["Q"]; sg = d["sg"]; assert sg[0] == Q and sg[-1] == 0
sgr = sg[1:]
L = []
L.append("import Mathlib.Tactic\n\n/-! # S10 data (generated by reports/S10_scratch/gen.py + export.py) -/\n\nset_option linter.style.longLine false\n\nnamespace Omega3\nnamespace S10\n")
L.append("/-- Cell left ends (in units of 1/Q, Q = 2^20). -/\ndef dEdges : List ℕ := [" + ", ".join(map(str, d["edges"])) + "]\n")
for i, ms in enumerate(d["ms"]):
    L.append(f"/-- Band {i}: values of the step function (in units of 1/10^5). -/\ndef dMs{i} : List ℤ := [" + ", ".join(map(str, ms)) + "]\n")
ch = [sgr[i:i+150] for i in range(0, len(sgr), 150)]
for k, c in enumerate(ch):
    L.append(f"def dSg{k} : List ℕ := [" + ", ".join(map(str, c)) + "]\n")
L.append("/-- The s-grid below `Q` (descending, ends at 0). -/\ndef dSg : List ℕ := " + " ++ ".join(f"dSg{k}" for k in range(len(ch))) + "\n")
L.append("/-- Band edges `x_i` as (numerator, denominator). -/\ndef dXs : List (ℕ × ℕ) := [" + ", ".join(f"({a}, {b})" for a, b in d["xs"]) + "]\n")
L.append("/-- Cost bounds `c_i − 1` in units of 10^-6. -/\ndef dCn : List ℕ := [" + ", ".join(str(b["cn"]) for b in d["bands"]) + "]\n")
L.append("end S10\nend Omega3\n")
open(sys.argv[2], "w").write("\n".join(L))
print(len(sgr), d["xs"], [b["cn"] for b in d["bands"]])
