"""Write Palprimes/Major1D/Data.lean: coefficient lists, cells, kernel checks (bases 4..9)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
import sys
sys.path.insert(0, HERE)
from fractions import Fraction as Fr
import cells as C, conds as K
OUT = os.path.join(HERE, '..', '..', '..', 'Palprimes', 'Major1D', 'Data.lean')
def q(x):
    x = Fr(x)
    return f'{x.numerator}' if x.denominator == 1 else f'{x.numerator} / {x.denominator}'
hdr = '''import Palprimes.Major1D.Poly

/-! # Major1D data: the 1D majorants for `b = 4, …, 9` and their kernel-checked cells

Generated by `lean/major1d/gen_lean.py` from `certdesign/majorants/final/maj1d_b*_H*_p*.json`.
`csB` are the numerators `c_0, …, c_{b−1}` over `2^52` of `T(t) = c_0 + 2 Σ_k c_k cos 2πkt`;
`cellsB` are `(hi, w, A, B)` covering `[−1, 1]` in the variable `c = cos 2πt`, checked by `chk`
against `ψ_b(c)^q`, `q = p/2`. -/

set_option linter.style.longLine false

namespace Palprimes
namespace M1D

/-- `τ_v = c_{|v|} / 2^52`. -/
def tq (cs : List ℕ) (v : ℤ) : ℚ := (cs.getD v.natAbs 0 : ℚ) / 2 ^ 52

/-- `T` in the Chebyshev variable: `Σ_{|v|<b} τ_v T_{|v|}`. -/
def mkPT (b : ℕ) (cs : List ℕ) : List ℚ :=
  mk (fun k => psmul (tq cs ((k : ℤ) - ((b : ℤ) - 1))) (cheb ((k : ℤ) - ((b : ℤ) - 1)).natAbs)) (2 * b - 1)

/-- `ψ_b` in the Chebyshev variable: `b^{−2} Σ_{i,j<b} T_{|i−j|}`. -/
def mkPsi (b : ℕ) : List ℚ :=
  psmul (1 / (b : ℚ) ^ 2) (mk (fun i => mk (fun j => cheb ((i : ℤ) - j).natAbs) b) b)

'''
body = ''
for b in range(4, 10):
    d, p, PT, Ppsi, cl = C.run(b)
    qq = p / 2
    cs = d['c']
    f = K.forms(b)
    body += f'/-! ## b = {b}, p = {p}, {len(cl)} cells -/\n\n'
    body += f'def cs{b} : List ℕ := [{", ".join(str(x) for x in cs)}]\n\n'
    body += f'def cells{b} : List (ℚ × ℚ × ℚ × ℚ) := [\n'
    body += ',\n'.join(f'  ({q(hi)}, {q(w)}, {q(A)}, {q(B)})' for (lo, hi, w, A, B) in cl)
    body += ']\n\n'
    body += f'theorem chk{b} : chk (mkPT {b} cs{b}) (mkPsi {b}) {qq.numerator} {qq.denominator} (-1) cells{b} = true := by\n  decide +kernel\n\n'
    body += f'theorem A{b} : qev (mkPT {b} cs{b}) 1 = ({f["Anum"]} : ℚ) / 2 ^ 52 := by decide +kernel\n\n'
    print(b, p, len(cl), f)
open(OUT, 'w').write(hdr + body + 'end M1D\nend Palprimes\n')
