def tail(nm,a,M,f,n,lits,Q):
    out=[]
    out.append(f"""theorem {nm}_total (δ : ℝ) (hδ : 0 < δ) :
    ∀ᶠ x : ℝ in Filter.atTop,
      ∑ p ∈ (Ioc ⌊x ^ ({a} 0)⌋₊ ⌊x ^ ({a} {n})⌋₊).filter Nat.Prime, {f} B x p ≤
        ({fr(Q)} + δ) * ∏ q ∈ PB B (Zc x), (1 - 1 / (q : ℝ)) := by
  have hloc : ∀ j < {n}, ∀ᶠ x : ℝ in Filter.atTop, ∀ p : ℕ, p.Prime → x ^ ({a} j) < p →
      (p : ℝ) ≤ x ^ ({a} (j + 1)) → {f} B x p ≤ max ({M} j) 0 * (∏ q ∈ PB B (Zc x), (1 - 1 / (q : ℝ))) / p := by
    intro j hj
    have key : ∀ (m : ℝ), (∀ᶠ x : ℝ in Filter.atTop, ∀ p : ℕ, p.Prime → x ^ ({a} j) < p →
        (p : ℝ) ≤ x ^ ({a} (j + 1)) → {f} B x p ≤ m * (∏ q ∈ PB B (Zc x), (1 - 1 / (q : ℝ))) / p) →
        m = {M} j → ∀ᶠ x : ℝ in Filter.atTop, ∀ p : ℕ, p.Prime → x ^ ({a} j) < p →
        (p : ℝ) ≤ x ^ ({a} (j + 1)) → {f} B x p ≤ max ({M} j) 0 * (∏ q ∈ PB B (Zc x), (1 - 1 / (q : ℝ))) / p := by
      intro m hm hmM
      filter_upwards [hm] with x hx p hp h1 h2
      refine le_trans (hx p hp h1 h2) ?_
      have hp0 : (0 : ℝ) < p := by exact_mod_cast hp.pos
      apply div_le_div_of_nonneg_right _ hp0.le
      exact mul_le_mul_of_nonneg_right (by rw [hmM]; exact le_max_left _ _) (V_PB_pos B (Zc x)).le
    interval_cases j""")
    for j in range(n):
        out.append(f"    · exact key _ ({nm}_c{j} C₂ C₃ c₁ hC₂ hC₃ hc₁ B hB).1 rfl")
    out.append(f"""  have hmax : ∀ (m l q : ℝ), m * l ≤ q → 0 ≤ q → max m 0 * l ≤ q := by
    intro m l q h hq
    rcases le_total m 0 with h0 | h0
    · rw [max_eq_right h0, zero_mul]; exact hq
    · rw [max_eq_left h0]; exact h
  have hsum : ∑ j ∈ range {n}, max ({M} j) 0 * Real.log ({a} (j + 1) / {a} j) ≤ {fr(Q)} := by
    simp only [Finset.sum_range_succ, Finset.sum_range_zero, zero_add, Nat.reduceAdd]""")
    hs=", ".join(f"hmax _ _ _ ({nm}_c{j} C₂ C₃ c₁ hC₂ hC₃ hc₁ B hB).2 (by norm_num)" for j in range(n))
    out.append(f"    linarith [{hs}]")
    out.append(f"""  have hg := grid_total C₂ hC₂ ({f} B) (fun x => ∏ q ∈ PB B (Zc x), (1 - 1 / (q : ℝ))) {n} {a}
    (fun j => max ({M} j) 0) (fun j => max ({M} j) 0 * Real.log ({a} (j + 1) / {a} j)) (by norm_num [{a}])
    {a}_mono (fun j _ => le_max_right _ _) hloc (fun j _ => le_rfl) δ hδ
  filter_upwards [hg] with x hx
  have hV := (V_PB_pos B (Zc x)).le
  refine le_trans (hx hV) ?_
  apply mul_le_mul_of_nonneg_right _ hV
  linarith
""")
    return "\n".join(out)
