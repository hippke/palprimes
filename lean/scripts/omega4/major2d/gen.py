"""major2d: generate Lean data files for the 2D kernel checker (tables, T terms, power tables, cell lists).
usage: gen.py b   (writes Palprimes/Major2D/B{b}Data.lean and, for b = 2, chunk files)"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
import sys, json, math
sys.path.insert(0, HERE)
import ref
import mpmath

LEAN = os.path.join(HERE, '..', '..', '..', 'Palprimes', 'Major2D') + os.sep
JS = {2: os.path.join(HERE, '..', 'majorants', "maj_b2_l7_p999_1000_th0.2608_final.json"),
      3: os.path.join(HERE, '..', 'majorants', "maj_b3_l3_p49_50_th0.2608_final.json")}
PAR = {2: dict(l=7, Q0=192, n0=1000, dmax=5), 3: dict(l=3, Q0=64, n0=50, dmax=5)}


def packtab(M):
    tab = ref.table(M)
    return sum((c + (s << 64)) << (128 * n) for n, (c, s) in enumerate(tab))


def lit(x, name, chunk_bits=8192):
    """a big Nat literal as a sum of shifted hex chunks."""
    parts = []
    i = 0
    while x:
        c = x & ((1 << chunk_bits) - 1)
        if c:
            parts.append(f"Nat.shiftLeft {hex(c)} {chunk_bits * i}")
        x >>= chunk_bits
        i += 1
    if not parts:
        parts = ["0"]
    body = " +\n  ".join(parts)
    return f"def {name} : ℕ :=\n  {body}\n"


def main(b):
    d, half = ref.load(JS[b])
    p = PAR[b]
    l, Q0, n0, dmax = p["l"], p["Q0"], p["n0"], p["dmax"]
    assert Fraction(d["p"]) == 1 - Fraction(1, n0)
    out = [f"import Palprimes.Major2D.Code\n\n/-! # Data for base {b} (generated by lean/major2d/gen.py) -/\n",
           "namespace Palprimes.M2\n"]
    out.append(f"/-- the majorant: doubled frequencies, coefficients over `2^52` (`(0,0)` once, others doubled). -/\n"
               f"def T{b}terms : List (ℤ × ℤ × ℕ) := [" + ", ".join(f"({U}, {V}, {c})" for (U, V, c) in half) + "]\n")
    for dd in range(dmax + 1):
        M = 4 * Q0 * 2 ** dd
        out.append(lit(packtab(M), f"tab{b}_{dd}"))
    out.append(f"def tab{b} : ℕ → ℕ\n" + "".join(f"  | {dd} => tab{b}_{dd}\n" for dd in range(dmax + 1)) + "  | _ => 0\n")
    pe = ref.PowEps(n0)
    out.append(f"def U2_{b} : ℕ := {pe.U2}\n")
    out.append(lit(sum(v << (128 * j) for j, v in enumerate(pe.V)), f"V{b}"))
    cells = ref.canonical(b, l, Q0)
    out.append(f"def L{b} : List (ℕ × ℕ) := [" + ", ".join(f"({j}, {k})" for (j, k) in cells) + "]\n")
    full = sorted(((u, v), n) for (u, v, n) in d["terms"])
    out.append(f"/-- the majorant, full list `((u, v), num)`, `τ_uv = num/2^52`. -/\n"
               f"def T{b}full : List ((ℤ × ℤ) × ℕ) := [" + ", ".join(f"(({u}, {v}), {n})" for ((u, v), n) in full) + "]\n")
    m = b * b - 1
    lam = [(a, c) for a in range(m) for c in range(m) if (a + b ** (l - 1) * c) % m == 0]
    out.append(f"def Lam{b} : List (ℕ × ℕ) := [" + ", ".join(f"({a}, {c})" for (a, c) in lam) + "]\n")
    out.append("end Palprimes.M2\n")
    open(LEAN + f"B{b}Data.lean", "w").write("\n".join(out))
    print("cells", len(cells), "terms", len(half))


from fractions import Fraction
if __name__ == "__main__":
    main(int(sys.argv[1]))
